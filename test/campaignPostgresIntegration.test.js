import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import pg from "pg";

const { Pool } = pg;
const migrationUrl = new URL("../docs/sql/027_campaign_test_trees.sql", import.meta.url);
const connectionString = process.env.PTB_CAMPAIGN_POSTGRES_INTEGRATION_URL;

function validatedLocalTestUrl(value) {
  if (!value) return null;
  const url = new URL(value);
  const localHosts = new Set(["localhost", "127.0.0.1", "[::1]", "::1"]);
  const database = decodeURIComponent(url.pathname.replace(/^\//, ""));
  if (!localHosts.has(url.hostname)) {
    throw new Error("PTB_CAMPAIGN_POSTGRES_INTEGRATION_URL must use localhost, 127.0.0.1 or ::1");
  }
  if (!/^ptb_campaign_test(?:_[a-z0-9_]+)?$/i.test(database)) {
    throw new Error("PTB_CAMPAIGN_POSTGRES_INTEGRATION_URL must target a dedicated ptb_campaign_test database");
  }
  return url.toString();
}

const localUrl = validatedLocalTestUrl(connectionString);

test("campaign allocation concurrency on isolated PostgreSQL", {
  skip: !localUrl && "local isolated PostgreSQL prerequisite unavailable"
}, async t => {
  const pool = new Pool({ connectionString: localUrl, max: 8, ssl: false });
  const migration = await readFile(migrationUrl, "utf8");

  const reset = async () => {
    await pool.query(`TRUNCATE TABLE
      public.campaign_orders,
      public.trees1,
      public.users1
      RESTART IDENTITY CASCADE`);
  };

  const seed = async ({ testTrees = 4, productionTrees = 2 } = {}) => {
    for (let n = 1; n <= productionTrees; n += 1) {
      await pool.query(`INSERT INTO public.trees1
        (tree_code, tree_type, area, lat, "long", is_test, is_claimed)
        VALUES ($1, 'Cashew', 'Production', 9, -12, false, false)`,
        [`REAL-CAMPAIGN-${String(n).padStart(4, "0")}`]);
    }
    for (let n = 1; n <= testTrees; n += 1) {
      await pool.query(`INSERT INTO public.trees1
        (tree_code, tree_type, area, lat, "long", is_test, is_claimed)
        VALUES ($1, 'TEST TREE – not a real planted tree', 'TEST ONLY', 0, -30, true, false)`,
        [`TEST-WZDB-${String(n).padStart(8, "0")}`]);
    }
  };

  const allocateTest = async (queryable, orderId, email = "training@example.invalid") => {
    const result = await queryable.query(`
      SELECT public.allocate_campaign_order(
        $1, 'PNB-WAAR-ZIJN-DE-BOMEN-TEST', '200', '201',
        1, 0, 'EUR', $2
      ) AS allocation
    `, [orderId, email]);
    return result.rows[0].allocation;
  };

  try {
    await pool.query("DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public");
    await pool.query(`CREATE TABLE public.users1 (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email text NOT NULL UNIQUE,
      created_at timestamp without time zone NOT NULL DEFAULT now(),
      updated_at timestamp without time zone NOT NULL DEFAULT now()
    )`);
    await pool.query(`CREATE TABLE public.trees1 (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tree_code text UNIQUE,
      tree_type text,
      area text,
      tree_name text,
      lat numeric,
      "long" numeric,
      planted_date date,
      user_id integer REFERENCES public.users1(id),
      order_id varchar(50),
      is_claimed boolean DEFAULT false,
      purchase_date timestamp without time zone,
      reserved_token text,
      claimed_token text,
      claimed_at timestamptz,
      unclaimed_user_id integer,
      created_at timestamp without time zone NOT NULL DEFAULT now(),
      updated_at timestamp without time zone NOT NULL DEFAULT now()
    )`);
    await pool.query(migration);
    await pool.query(`INSERT INTO public.campaign_products
      (sku, product_id, variant_id, is_test, unit_price, enabled)
      VALUES
      ('PNB-WAAR-ZIJN-DE-BOMEN', '100', '101', false, 10, true),
      ('PNB-WAAR-ZIJN-DE-BOMEN-TEST', '200', '201', true, 0, true)`);

    await t.test("concurrent distinct TEST orders allocate distinct fake trees only", async () => {
      await reset();
      await seed({ testTrees: 4, productionTrees: 2 });

      const [a, b] = await Promise.all([
        allocateTest(pool, "70000000001", "a@example.invalid"),
        allocateTest(pool, "70000000002", "b@example.invalid")
      ]);

      const codes = [a.assigned_trees[0].tree_code, b.assigned_trees[0].tree_code];
      assert.equal(new Set(codes).size, 2);
      assert.ok(codes.every(code => code.startsWith("TEST-WZDB-")));

      const productionAllocated = await pool.query(
        "SELECT count(*)::int AS n FROM public.trees1 WHERE is_test=false AND user_id IS NOT NULL"
      );
      assert.equal(productionAllocated.rows[0].n, 0);
    });

    await t.test("concurrent duplicate TEST order is idempotent", async () => {
      await reset();
      await seed({ testTrees: 3, productionTrees: 1 });

      const [a, b] = await Promise.all([
        allocateTest(pool, "70000000003"),
        allocateTest(pool, "70000000003")
      ]);

      assert.deepEqual(a.assigned_trees, b.assigned_trees);
      assert.equal([a.duplicate, b.duplicate].filter(Boolean).length, 1);

      const ledger = await pool.query(
        "SELECT count(*)::int AS n FROM public.campaign_orders WHERE order_id='70000000003'"
      );
      assert.equal(ledger.rows[0].n, 1);

      const allocated = await pool.query(
        "SELECT count(*)::int AS n FROM public.trees1 WHERE order_id='70000000003'"
      );
      assert.equal(allocated.rows[0].n, 1);
    });

    await t.test("SKIP LOCKED avoids a locked fake tree and never crosses into production", async () => {
      await reset();
      await seed({ testTrees: 2, productionTrees: 2 });

      const firstTestTree = (await pool.query(
        "SELECT id FROM public.trees1 WHERE is_test=true ORDER BY id LIMIT 1"
      )).rows[0].id;

      const locker = await pool.connect();
      try {
        await locker.query("BEGIN");
        await locker.query("SELECT id FROM public.trees1 WHERE id=$1 FOR UPDATE", [firstTestTree]);

        const result = await allocateTest(pool, "70000000004");
        assert.notEqual(result.assigned_trees[0].tree_id, firstTestTree);
        assert.equal(result.assigned_trees[0].is_test, true);

        const productionAllocated = await pool.query(
          "SELECT count(*)::int AS n FROM public.trees1 WHERE is_test=false AND user_id IS NOT NULL"
        );
        assert.equal(productionAllocated.rows[0].n, 0);
      } finally {
        await locker.query("ROLLBACK");
        locker.release();
      }
    });

    await t.test("empty TEST pool fails while production inventory remains untouched", async () => {
      await reset();
      await seed({ testTrees: 0, productionTrees: 2 });

      const before = (await pool.query(
        "SELECT id, user_id, order_id, is_claimed, purchase_date, claimed_at FROM public.trees1 WHERE is_test=false ORDER BY id"
      )).rows;

      await assert.rejects(allocateTest(pool, "70000000005"), /TEST_POOL_EMPTY/);

      const after = (await pool.query(
        "SELECT id, user_id, order_id, is_claimed, purchase_date, claimed_at FROM public.trees1 WHERE is_test=false ORDER BY id"
      )).rows;
      assert.deepEqual(after, before);

      const ledger = await pool.query(
        "SELECT count(*)::int AS n FROM public.campaign_orders WHERE order_id='70000000005'"
      );
      assert.equal(ledger.rows[0].n, 0);
    });
  } finally {
    await pool.query("DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public").catch(() => {});
    await pool.end();
  }
});

export { validatedLocalTestUrl };
